/**
 * Issue #343 — writes docs/permissions.md from the role table (packages/platform/src/roles.ts) and
 * the route table (apps/api/src/routes, #344). Run `npm run permissions:docs` after changing either;
 * tools/test/permissions-doc.test.ts fails while the file and the code disagree.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ROUTES } from '../../apps/api/src/routes/index.ts';
import type { Route } from '../../apps/api/src/routes/route.ts';
import { ROLE_NAMES, ROLES } from '../../packages/platform/src/roles.ts';
import type { Permission } from '../../packages/platform/src/types.ts';

export const PERMISSIONS_DOC = new URL('../../docs/permissions.md', import.meta.url);

const permits = (route: Route, held: readonly Permission[]): boolean => {
  if (route.access.kind !== 'gate') return route.access.kind !== 'public';
  const { all, any } = route.access;
  return all.every((permission) => held.includes(permission)) && (any.length === 0 || any.some((permission) => held.includes(permission)));
};
const needs = (route: Route): string => {
  if (route.access.kind === 'public') return `nobody signed in: ${route.access.reason}`;
  if (route.access.kind === 'signedIn') return `any member: ${route.access.reason}`;
  const { all, any } = route.access;
  return [...all.map((permission) => `\`${permission}\``), ...(any.length === 0 ? [] : [any.map((permission) => `\`${permission}\``).join(' or ')])].join(' + ');
};

export const permissionsDoc = (): string => {
  const permissions = [...new Set(ROLE_NAMES.flatMap((role) => ROLES[role].permissions))].sort();
  const roleHeader = ROLE_NAMES.map((role) => ROLES[role].title).join(' | ');
  const lines = [
    '# Who may do what',
    '',
    '<!-- Generated by `npm run permissions:docs` from packages/platform/src/roles.ts and the route table in apps/api/src/routes. Do not edit by hand. -->',
    '',
    'Issue #343. Every API route names the permission it needs, and the server checks it on every request: no session is **401**, a permission the person does not hold is **403**, and another business\'s record is **404** (it is not said to exist). The tests that prove each row are generated from the same tables (`apps/api/test/route-matrix.test.ts`).',
    '',
    '## Roles',
    '',
    '| Role | What it is for |',
    '| --- | --- |',
    ...ROLE_NAMES.map((role) => `| ${ROLES[role].title} | ${ROLES[role].sentence} |`),
    '',
    'A chartered accountant who looks after several businesses is an **Accountant** in each: one sign-in, one membership per business, switching between them without signing in again. Only an owner can make someone an admin, change or remove an owner or admin, or hand the business over; nobody is made an owner directly, and the last owner cannot leave. Invitations last 7 days and can be taken up only by the phone number or email they were sent to.',
    '',
    '## Role × permission',
    '',
    `| Permission | ${roleHeader} |`,
    `| --- | ${ROLE_NAMES.map(() => ':---:').join(' | ')} |`,
    ...permissions.map((permission) => `| \`${permission}\` | ${ROLE_NAMES.map((role) => ROLES[role].permissions.includes(permission) ? '✓' : '').join(' | ')} |`),
    '',
    `## Routes (${ROUTES.length})`,
    '',
    `| Route | Needs | ${roleHeader} |`,
    `| --- | --- | ${ROLE_NAMES.map(() => ':---:').join(' | ')} |`,
    ...ROUTES.map((route) => `| \`${route.method} ${route.path}\` | ${needs(route)} | ${ROLE_NAMES.map((role) => route.access.kind === 'public' ? '—' : permits(route, ROLES[role].permissions) ? '✓' : '').join(' | ')} |`),
    '',
  ];
  return lines.join('\n');
};

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(PERMISSIONS_DOC, permissionsDoc());
  console.log('Wrote docs/permissions.md');
}
